//! Contrato OpenAPI e normalização dos erros HTTP de `POST /mcp` (portado do sap-middleman).

use axum::{
    extract::Request,
    http::{HeaderValue, StatusCode, header},
    middleware::Next,
    response::{IntoResponse, Response},
};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use utoipa::ToSchema;

use crate::error::{ApiError, ErrorResponse};

/// JSON-RPC 2.0 message sent by an MCP client.
#[derive(Debug, Deserialize, Serialize, ToSchema)]
#[schema(example = json!({
    "jsonrpc": "2.0",
    "id": 1,
    "method": "tools/call",
    "params": {"name": "get_guide", "arguments": {"guide": "tokens-e-escopos", "section": "Escopos"}}
}))]
pub struct McpJsonRpcRequest {
    /// Always `2.0`.
    #[schema(example = "2.0")]
    pub jsonrpc: String,
    /// Request identifier (string or integer). Omitted for notifications.
    #[schema(value_type = Option<Object>)]
    pub id: Option<Value>,
    /// MCP method: `initialize`, `notifications/initialized`, `ping`, `tools/list` or `tools/call`.
    #[schema(example = "tools/call")]
    pub method: String,
    /// Method parameters defined by the MCP specification.
    #[schema(value_type = Option<Object>)]
    pub params: Option<Value>,
}

/// JSON-RPC 2.0 error object.
#[derive(Debug, Deserialize, Serialize, ToSchema)]
pub struct McpJsonRpcError {
    /// JSON-RPC error code, for example `-32602` for invalid tool arguments.
    #[schema(example = -32602)]
    pub code: i32,
    #[schema(example = "argumentos invalidos")]
    pub message: String,
    /// Optional diagnostic data.
    #[schema(value_type = Option<Object>)]
    pub data: Option<Value>,
}

/// JSON-RPC 2.0 response returned by the MCP server.
#[derive(Debug, Deserialize, Serialize, ToSchema)]
pub struct McpJsonRpcResponse {
    #[schema(example = "2.0")]
    pub jsonrpc: String,
    #[schema(value_type = Object)]
    pub id: Value,
    /// Method result, for example `{ "content": [...], "structuredContent": {...} }` for
    /// `tools/call`. Domain errors come as `isError: true` with the standard error envelope in
    /// `structuredContent`.
    #[schema(value_type = Option<Object>)]
    pub result: Option<Value>,
    pub error: Option<McpJsonRpcError>,
}

#[utoipa::path(
    post,
    path = "/mcp",
    operation_id = "mcp",
    tag = "MCP",
    summary = "MCP de operações e documentação (Streamable HTTP, stateless)",
    description = "Model Context Protocol para agentes de IA. Expõe as operações do Engramind como ferramentas, com os mesmos nomes, parâmetros, escopos e códigos de erro do REST, e as ferramentas de documentação da versão em execução. `tools/list` mostra só as ferramentas que o token pode usar; chamar uma ferramenta oculta devolve o mesmo `SCOPE_REQUIRED` do REST. Erros de domínio voltam com `isError: true` e o envelope `{ error: { code, message, details } }` em `structuredContent`. Mutações aceitam `idempotency_key`. Sem sessões nem SSE: cada POST leva uma mensagem JSON-RPC e recebe `application/json`. O cliente envia `Accept: application/json, text/event-stream`. Falhas HTTP usam o envelope padrão.",
    request_body(content = McpJsonRpcRequest, content_type = "application/json"),
    security(("bearerAuth" = [])),
    responses(
        (status = 200, description = "Resposta JSON-RPC", body = McpJsonRpcResponse, content_type = "application/json"),
        (status = 202, description = "Notificação aceita, sem corpo"),
        (status = 400, description = "Cabeçalhos ou mensagem MCP inválidos (`MCP_BAD_REQUEST`)", body = ErrorResponse),
        (status = 401, description = "`AUTH_INVALID`", body = ErrorResponse),
        (status = 403, description = "`Host` fora de `MCP_ALLOWED_HOSTS` (`MCP_HOST_FORBIDDEN`)", body = ErrorResponse),
        (status = 406, description = "`Accept` precisa incluir application/json e text/event-stream (`MCP_NOT_ACCEPTABLE`)", body = ErrorResponse),
        (status = 413, description = "`PAYLOAD_TOO_LARGE`", body = ErrorResponse),
        (status = 415, description = "`Content-Type` precisa ser application/json (`MCP_UNSUPPORTED_MEDIA_TYPE`)", body = ErrorResponse),
        (status = 422, description = "Mensagem JSON-RPC inesperada (`MCP_INVALID_MESSAGE`)", body = ErrorResponse),
        (status = 429, description = "`RATE_LIMITED`", body = ErrorResponse),
        (status = 500, description = "`INTERNAL_ERROR`", body = ErrorResponse),
        (status = 503, description = "`DATABASE_UNAVAILABLE` durante a autenticação", body = ErrorResponse),
        (status = 504, description = "`REQUEST_TIMEOUT`", body = ErrorResponse)
    )
)]
pub async fn mcp_contract() {}

const MAX_REASON_BYTES: usize = 512;
const MAX_REASON_CHARS: usize = 200;

/// Reads the short diagnostic text produced by the MCP transport. The text is
/// generated by the protocol library, never contains request bodies or
/// credentials, and is bounded before being returned.
async fn transport_reason(response: Response) -> Option<String> {
    let bytes = axum::body::to_bytes(response.into_body(), MAX_REASON_BYTES)
        .await
        .ok()?;
    let text = String::from_utf8_lossy(&bytes);
    let reason: String = text
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .chars()
        .filter(|character| !character.is_control())
        .take(MAX_REASON_CHARS)
        .collect();
    (!reason.is_empty()).then_some(reason)
}

/// Converts the plain-text HTTP errors produced by the MCP transport into the
/// standard error envelope. JSON responses (JSON-RPC) pass through unchanged.
pub async fn normalize_transport_errors(request: Request, next: Next) -> Response {
    let response = next.run(request).await;
    let status = response.status();
    if !(status.is_client_error() || status.is_server_error()) {
        return response;
    }
    let is_json = response
        .headers()
        .get(header::CONTENT_TYPE)
        .and_then(|value| value.to_str().ok())
        .is_some_and(|value| value.starts_with("application/json"));
    if is_json {
        return response;
    }
    let allow = response.headers().get(header::ALLOW).cloned();
    let reason = transport_reason(response).await;
    let error = match status {
        StatusCode::BAD_REQUEST => ApiError::new("MCP_BAD_REQUEST", "Requisicao MCP invalida"),
        StatusCode::FORBIDDEN => {
            ApiError::new("MCP_HOST_FORBIDDEN", "Host nao permitido para o MCP")
        }
        StatusCode::NOT_FOUND => ApiError::route_not_found(),
        StatusCode::METHOD_NOT_ALLOWED => {
            ApiError::new("METHOD_NOT_ALLOWED", "Use POST para o MCP")
        }
        StatusCode::NOT_ACCEPTABLE => ApiError::new(
            "MCP_NOT_ACCEPTABLE",
            "Accept deve incluir application/json e text/event-stream",
        ),
        StatusCode::PAYLOAD_TOO_LARGE => ApiError::payload_too_large(),
        StatusCode::UNSUPPORTED_MEDIA_TYPE => ApiError::new(
            "MCP_UNSUPPORTED_MEDIA_TYPE",
            "Content-Type deve ser application/json",
        ),
        StatusCode::UNPROCESSABLE_ENTITY => {
            ApiError::new("MCP_INVALID_MESSAGE", "Mensagem JSON-RPC inesperada")
        }
        _ if status.is_server_error() => ApiError::internal(),
        _ => ApiError::new("MCP_BAD_REQUEST", "Requisicao MCP invalida"),
    };
    let error = match reason {
        Some(reason) => error.with_details(serde_json::json!({ "reason": reason })),
        None => error,
    };
    let mut normalized = error.into_response();
    if let Some(allow) = allow {
        normalized.headers_mut().insert(header::ALLOW, allow);
    } else if status == StatusCode::METHOD_NOT_ALLOWED {
        normalized
            .headers_mut()
            .insert(header::ALLOW, HeaderValue::from_static("POST"));
    }
    normalized
}
